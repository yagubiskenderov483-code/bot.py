function EuropeGrid.CellToWorld(col: number, row: number): Vector3
	local size = EuropeGrid.CellSize
	local x = (col - EuropeGrid.Cols / 2) * size
	local z = (row - EuropeGrid.Rows / 2) * size
	return Vector3.new(x, 0, z)
end

function EuropeGrid.GetCountryAt(col: number, row: number): string?
	for _, cell in ipairs(EuropeGrid.Cells) do
		if cell[1] == col and cell[2] == row then
			return cell[3]
		end
	end
	return nil
end

function EuropeGrid.GetFirstLandCell(): (number, number)
	-- Франция / центр Европы — безопасный спавн
	return 20, 24
end

